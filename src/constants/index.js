export const calculateSizes = (isSmall, isMobile, isTablet) => {
  return {
    // 1. حجم الموديل (Scale)
    aseemScale: isSmall ? 0.75 : isMobile ? 1.0 : isTablet ? 1.2 : 1.35,

    reactLogoScale: isSmall ? 0.4 : isMobile ? 0.4 : isTablet ? 0.5 : 0.6,

    targetScale: isSmall ? 20 : isMobile ? 20 : isTablet ? 25 : 30,

    // 2. موقع الموديل (Position: [X, Y, Z])
    // نخليه متسنتر في الـ X = 0 وننزله شوية في الـ Y
    aseemPosition: isSmall
      ? [1, 0, 1]
      : isMobile
        ? [2, -1, 2]
        : isTablet
          ? [3, -2, 2]
          : [2, -3.5, 2],

    // 3. دوران الموديل المبدئي (Rotation: [X, Y, Z])
    aseemRotation: [0.12, 0.4, 0],

    // باقي العناصر المرافقة (لو بتستخدمها في المشهد)
    cubePosition: isSmall
      ? [3, -3.5, 0]
      : isMobile
        ? [4, -4, 0]
        : isTablet
          ? [5, -4, 0]
          : [7.5, -4.5, 0],
    reactLogoPosition: isSmall
      ? [4, 5, 0]
      : isMobile
        ? [6.5, 4.5, -2]
        : isTablet
          ? [11, 4, -5]
          : [14.5, 3, 0],
    ringPosition: isSmall
      ? [-4, 6, 0]
      : isMobile
        ? [8, -6, 0]
        : isTablet
          ? [10, -8, 0]
          : [15, -9.5, 0],
    targetPosition: isSmall
      ? [5, -3, -5]
      : isMobile
        ? [5, -3, -5]
        : isTablet
          ? [-12, -10, -5]
          : [-20, -9, -5],
  };
};

